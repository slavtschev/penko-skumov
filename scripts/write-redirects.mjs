/**
 * Write dist/_redirects for Netlify.
 *
 * Every address the Webflow site answered on has to keep working: links
 * from elsewhere, bookmarks, and whatever search engines have indexed.
 * The series lines are generated from the content, from the `legacyPage`
 * each series carries, so the list cannot drift from the real one -- and
 * that includes `lith-prints.html.html`, which the old Archive page
 * linked with the extension doubled.
 *
 * 301, because these moves are permanent.
 */
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const FIXED = [
  ['/index.html', '/'],
  ['/projects.html', '/projects/'],
  /* the Archive is no longer its own page; its series live under
     /projects/ and the list groups them */
  ['/archive.html', '/projects/'],
  ['/about.html', '/about/'],
  ['/contact.html', '/contact/'],
];

export async function writeRedirects(distDir, seriesDir, log = console) {
  const lines = [];
  const add = (from, to) => lines.push(`${from.padEnd(34)} ${to.padEnd(40)} 301`);

  for (const [from, to] of FIXED) add(from, to);

  const files = (await readdir(seriesDir)).filter((f) => f.endsWith('.json')).sort();
  let series = 0;
  for (const file of files) {
    const data = JSON.parse(await readFile(join(seriesDir, file), 'utf8'));
    if (!data.legacyPage) continue; // Film Archive never had a page
    add(`/${data.legacyPage}`, `/projects/${data.slug}/`);
    series++;
    /* the old Archive page linked Lith Prints with the extension twice */
    if (data.slug === 'lith-prints') {
      add(`/${data.legacyPage}.html`, `/projects/${data.slug}/`);
    }
  }

  const body =
    '# Generated by scripts/write-redirects.mjs -- do not edit by hand.\n' +
    '# Every address the Webflow site answered on, kept working.\n\n' +
    lines.join('\n') +
    '\n';

  await writeFile(join(distDir, '_redirects'), body);
  log.info(`wrote _redirects: ${FIXED.length} pages, ${series} series`);
  return lines.length;
}

/** @type {() => import('astro').AstroIntegration} */
export const redirects = () => ({
  name: 'write-redirects',
  hooks: {
    'astro:build:done': async ({ dir, logger }) => {
      await writeRedirects(dir.pathname, new URL('../src/content/series/', import.meta.url).pathname, logger);
    },
  },
});
